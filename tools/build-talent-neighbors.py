#!/usr/bin/env python3
"""Export Talent's observed per-image neighbors for the converter."""

import argparse
from datetime import date
import json
from pathlib import Path
import re


MIN_CONTACTS = 50
CATALOG_NAME = "TALENT_PALETTE_DATA"


def pair_id(indices):
    if (not isinstance(indices, list) or len(indices) != 2
            or any(type(index) is not int or not 0 <= index < 16 for index in indices)):
        raise ValueError("A color pair must contain two C64 color indices.")
    return "-".join(map(str, sorted(indices)))


def source_pair_id(value):
    if not isinstance(value, str) or not re.fullmatch(r"\d+-\d+", value):
        raise ValueError("Analysis edge has an invalid color-pair ID.")
    return pair_id([int(index) for index in value.split("-")])


def read_catalog(path):
    # This catalogue is data with bare object keys. Parse its restricted literal
    # as JSON instead of executing JavaScript or requiring a browser runtime.
    source = path.read_text(encoding="utf-8")
    literal = re.fullmatch(r"\s*(?:/\*.*?\*/\s*)?const\s+" + CATALOG_NAME
                           + r"\s*=\s*(\{.*\})\s*;\s*", source, re.DOTALL)
    if literal is None:
        raise ValueError(f"{path}: expected a {CATALOG_NAME} data declaration.")
    quoted_keys = re.sub(r'([,{]\s*)([A-Za-z_$][\w$]*)(\s*:)',
                         r'\1"\2"\3', literal.group(1))
    catalog = json.loads(quoted_keys)
    pairs = catalog.get("pairs")
    if not isinstance(pairs, list) or not pairs:
        raise ValueError("Catalogue must contain a nonempty pairs array.")
    allowed = {pair_id(pair["colorIndices"]) for pair in pairs}
    if len(allowed) != len(pairs):
        raise ValueError("Catalogue contains duplicate color pairs.")
    analysis_date = catalog["source"]["analysisDate"]
    date.fromisoformat(analysis_date)
    return allowed, analysis_date


def contact_count(edge, field):
    value = edge.get(field)
    if type(value) is not int or value < 0:
        raise ValueError(f"Analysis edge has an invalid {field} count.")
    return value


def build_neighbors(analysis, allowed, analysis_date):
    images = analysis.get("images")
    if not isinstance(images, list) or not images:
        raise ValueError("Analysis must contain a nonempty images array.")
    method = analysis.get("method", {})
    if method.get("unique_image_count") != len(images):
        raise ValueError("Analysis image count does not match its method metadata.")
    exported = []
    seen_image_ids = set()
    for image in images:
        image_id = image.get("id")
        if type(image_id) is not int or image_id < 1 or image_id in seen_image_ids:
            raise ValueError("Analysis image IDs must be unique positive integers.")
        seen_image_ids.add(image_id)
        if not isinstance(image.get("edges"), list):
            raise ValueError(f"Image {image_id} must contain an edges array.")
        edges = []
        seen_edges = set()
        for edge in image["edges"]:
            a, b = sorted((source_pair_id(edge["a"]), source_pair_id(edge["b"])),
                          key=lambda value: tuple(map(int, value.split("-"))))
            count = contact_count(edge, "count")
            if contact_count(edge, "horizontal") + contact_count(edge, "vertical") != count:
                raise ValueError(f"Image {image_id}: edge total differs from its direction counts.")
            if a == b or (a, b) in seen_edges:
                raise ValueError(f"Image {image_id}: duplicate or same-pair edge.")
            seen_edges.add((a, b))
            if a in allowed and b in allowed and count >= MIN_CONTACTS:
                edges.append({"a": a, "b": b, "count": count})
        edges.sort(key=lambda edge: tuple(map(int, (edge["a"] + "-" + edge["b"]).split("-"))))
        exported.append({"id": image_id, "edges": edges})
    exported.sort(key=lambda image: image["id"])
    return {"minContacts": MIN_CONTACTS,
            "source": {"analysisDate": analysis_date, "uniqueImageCount": len(images),
                       "description": "Observed per-image color-pair contacts from supplied Talent artwork; "
                                      "counts combine horizontal and vertical contacts."},
            "images": exported}


def render(data):
    lines = ["/** Generated by tools/build-talent-neighbors.py; observed contacts, not proven gradients. */",
             "const TALENT_NEIGHBOR_DATA = {",
             f'  minContacts: {data["minContacts"]},',
             '  source: ' + json.dumps(data["source"], separators=(",", ":")) + ",",
             "  images: ["]
    lines.extend("    " + json.dumps(image, separators=(",", ":"))
                 + ("," if position < len(data["images"]) - 1 else "")
                 for position, image in enumerate(data["images"]))
    return "\n".join([*lines, "  ]", "};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--analysis", type=Path, required=True, help="Full analyze-dither-pairs.py JSON output.")
    parser.add_argument("--catalog", type=Path,
                        default=Path(__file__).resolve().parents[1] / "talent-palette.js")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        allowed, analysis_date = read_catalog(args.catalog)
        analysis = json.loads(args.analysis.read_text(encoding="utf-8"))
        data = build_neighbors(analysis, allowed, analysis_date)
        output = render(data)
        args.output.write_text(output, encoding="utf-8")
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.error(str(error))
    print(f'{len(data["images"])} images; {len(allowed)} allowed pairs; '
          f'{sum(len(image["edges"]) for image in data["images"])} per-image links; '
          f'{len(output.encode("utf-8"))} bytes. Output: {args.output}')


if __name__ == "__main__":
    main()
