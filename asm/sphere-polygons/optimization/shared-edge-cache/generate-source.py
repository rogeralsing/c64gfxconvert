#!/usr/bin/env python3
"""Clone the frozen raster and attach live, same-frame shared-edge caching."""
from pathlib import Path
import json

HERE = Path(__file__).resolve().parent
BASE = HERE.parents[1]
source = (BASE / "raster.asm").read_text()
edge = source[source.index("raster_edge:\n"):source.index("// Advance directly")]

dispatch = """    lda shared_cache_ready
    bne !cache_initialized+
    jsr delta_init
!cache_initialized:
    lda model
    beq !uncached+
    jsr shared_begin_frame
    lda #<raster_cached_edge
    sta shared_edge_call+1
    lda #>raster_cached_edge
    bne !dispatch+
!uncached:
    lda #<raster_edge
    sta shared_edge_call+1
    lda #>raster_edge
!dispatch:
    sta shared_edge_call+2
"""
source = source.replace("render_polygons:\n", "render_polygons:\n" + dispatch, 1)
source = source.replace("!edge:\n    jsr raster_edge", "!edge:\nshared_edge_call:\n    jsr raster_edge", 1)
source = source.replace("!active:\n    ldx raster_dy", "!active:\nraster_edge_uncached_active:\n    ldx raster_dy", 1)
source = ".label shared_cache_position = $31\n.label shared_cache_ptr = $32\n" + source
(HERE / "raster.asm").write_text(source)

cached = edge.replace("raster_edge:\n", "raster_cached_edge:\n", 1)
cached = cached.replace("!active:\n", """!active:
    // Each football white hexagon has three white neighbours. Static topology
    // identifies those edges; the actual curve always comes from this frame.
    lda face_ptr
    sec
    sbc #<football_faces
    lsr
    clc
    adc raster_edge_index
    tax
    lda shared_topology_ids,x
    cmp #255
    bne !shared+
    jmp raster_edge_uncached_active
!shared:
    tax
    jsr shared_edge_lookup
    bcc !generate+
    rts
!generate:
""", 1)
cached = cached.replace("!ceil_ready:\n", """!ceil_ready:
    // Cache the absolute crossing generated by this edge's live rational DDA.
    ldy shared_cache_position
    sta (shared_cache_ptr),y
    inc shared_cache_position
""", 1)
ids = json.loads((HERE / "topology.json").read_text())["faceEdgeIds"]
header = """// Shared white/white edges, reused only within one live frame. No animation
// data or host-generated curve appears in the program. All misses run the DDA.
.const SHARED_CACHE_SLOTS = 32
.const SHARED_CURVE_LENGTH = 24
.const SHARED_CACHE_RAM = $e000
.const SHARED_CURVES = SHARED_CACHE_RAM + SHARED_CACHE_SLOTS
.const SHARED_SCRATCH = SHARED_CURVES + SHARED_CACHE_SLOTS*SHARED_CURVE_LENGTH
.const SHARED_CACHE_STATE_BYTES = SHARED_CACHE_SLOTS + SHARED_CACHE_SLOTS*SHARED_CURVE_LENGTH + 128
.label shared_cache_tags = SHARED_CACHE_RAM
.assert "Private cache state must not overlap hardware vectors", SHARED_SCRATCH+128 <= $fffa, true

* = $c000 "Same-frame shared-edge helpers"
delta_init:
    lda #0
    sta shared_generation
    ldx #SHARED_CACHE_SLOTS-1
!clear:
    sta shared_cache_tags,x
    dex
    bpl !clear-
    lda #1
    sta shared_cache_ready
    rts

shared_begin_frame:
    inc shared_generation
    bne !done+
    // Avoid an old generation alias after a full byte wrap. This work counts.
    lda #0
    ldx #SHARED_CACHE_SLOTS-1
!clear:
    sta shared_cache_tags,x
    dex
    bpl !clear-
    inc shared_generation
!done:
    rts

shared_edge_lookup:
    lda #0
    sta shared_cache_position
    lda raster_edge_end
    sec
    sbc raster_edge_first
    cmp #SHARED_CURVE_LENGTH+1
    bcc !cacheable+
    lda #<SHARED_SCRATCH
    sta shared_cache_ptr
    lda #>SHARED_SCRATCH
    sta shared_cache_ptr+1
    clc
    rts
!cacheable:
    lda shared_curve_pointer_lo,x
    sta shared_cache_ptr
    lda shared_curve_pointer_hi,x
    sta shared_cache_ptr+1
    lda shared_cache_tags,x
    cmp shared_generation
    bne !miss+
    ldx raster_edge_first
    ldy #0
!sample:
    lda (shared_cache_ptr),y
    cmp span_left,x
    bcs !not_left+
    sta span_left,x
!not_left:
    cmp span_right,x
    bcc !not_right+
    sta span_right,x
!not_right:
    iny
    inx
    cpx raster_edge_end
    bcc !sample-
    stx raster_edge_sample
    sec
    rts
!miss:
    lda shared_generation
    sta shared_cache_tags,x
    clc
    rts

"""
footer = """
shared_generation: .byte 0
shared_cache_ready: .byte 0
shared_curve_pointer_lo:
    .fill SHARED_CACHE_SLOTS, <(SHARED_CURVES+i*SHARED_CURVE_LENGTH)
shared_curve_pointer_hi:
    .fill SHARED_CACHE_SLOTS, >(SHARED_CURVES+i*SHARED_CURVE_LENGTH)
shared_topology_ids:
"""
for i in range(0, len(ids), 12):
    footer += "    .byte " + ",".join(map(str, ids[i:i+12])) + "\n"
footer += '\n.assert "Shared-edge helpers must remain below I/O", * <= $d000, true\n'
(HERE / "extra.asm").write_text(header + cached + footer)
