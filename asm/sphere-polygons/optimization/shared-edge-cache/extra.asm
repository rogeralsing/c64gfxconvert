// Shared white/white edges, reused only within one live frame. No animation
// data or host-generated curve appears in the program. All misses run the DDA.
.const SHARED_CACHE_SLOTS = 32
.const SHARED_CURVE_LENGTH = 24
.const SHARED_CACHE_RAM = $e000
.const SHARED_CURVES = SHARED_CACHE_RAM + SHARED_CACHE_SLOTS
.const SHARED_SCRATCH = SHARED_CURVES + SHARED_CACHE_SLOTS*SHARED_CURVE_LENGTH
.const SHARED_CACHE_STATE_BYTES = SHARED_CACHE_SLOTS + SHARED_CACHE_SLOTS*SHARED_CURVE_LENGTH + 128
.label shared_cache_tags = SHARED_CACHE_RAM
.assert "Private cache state must not overlap hardware vectors", SHARED_SCRATCH+128 <= $fffa, true

* = $c000 "Same-frame shared-edge helpers"
delta_init:
    lda #0
    sta shared_generation
    ldx #SHARED_CACHE_SLOTS-1
!clear:
    sta shared_cache_tags,x
    dex
    bpl !clear-
    lda #1
    sta shared_cache_ready
    rts

shared_begin_frame:
    inc shared_generation
    bne !done+
    // Avoid an old generation alias after a full byte wrap. This work counts.
    lda #0
    ldx #SHARED_CACHE_SLOTS-1
!clear:
    sta shared_cache_tags,x
    dex
    bpl !clear-
    inc shared_generation
!done:
    rts

shared_edge_lookup:
    lda #0
    sta shared_cache_position
    lda raster_edge_end
    sec
    sbc raster_edge_first
    cmp #SHARED_CURVE_LENGTH+1
    bcc !cacheable+
    lda #<SHARED_SCRATCH
    sta shared_cache_ptr
    lda #>SHARED_SCRATCH
    sta shared_cache_ptr+1
    clc
    rts
!cacheable:
    lda shared_curve_pointer_lo,x
    sta shared_cache_ptr
    lda shared_curve_pointer_hi,x
    sta shared_cache_ptr+1
    lda shared_cache_tags,x
    cmp shared_generation
    bne !miss+
    ldx raster_edge_first
    ldy #0
!sample:
    lda (shared_cache_ptr),y
    cmp span_left,x
    bcs !not_left+
    sta span_left,x
!not_left:
    cmp span_right,x
    bcc !not_right+
    sta span_right,x
!not_right:
    iny
    inx
    cpx raster_edge_end
    bcc !sample-
    stx raster_edge_sample
    sec
    rts
!miss:
    lda shared_generation
    sta shared_cache_tags,x
    clc
    rts

raster_cached_edge:
    lda raster_edge_index
    clc
    adc #5
    tay
    lda (face_ptr),y
    tax
    lda projected_x,x
    sta raster_x0
    lda projected_y,x
    sta raster_y0
    lda raster_edge_index
    clc
    adc #1
    cmp raster_vertex_count
    bcc !not_last+
    lda #0
!not_last:
    clc
    adc #5
    tay
    lda (face_ptr),y
    tax
    lda projected_x,x
    sta raster_x1
    lda projected_y,x
    sta raster_y1
    cmp raster_y0
    bne !not_horizontal+
    rts
!not_horizontal:
    bcs !ordered+
    ldx raster_x0
    lda raster_x1
    sta raster_x0
    stx raster_x1
    ldx raster_y0
    lda raster_y1
    sta raster_y0
    stx raster_y1
!ordered:
    lda raster_y1
    sec
    sbc raster_y0
    sta raster_dy
    lda raster_x1
    sec
    sbc raster_x0
    bcs !positive+
    eor #255
    clc
    adc #1
    sta raster_dx
    lda #1
    bne !direction+
!positive:
    sta raster_dx
    lda #0
!direction:
    sta raster_negative
    ldx raster_y0
    lda first_sample,x
    sta raster_edge_first
    sta raster_edge_sample
    ldx raster_y1
    lda first_sample,x
    sta raster_edge_end
    cmp raster_edge_first
    bne !active+
    rts
!active:
    // Each football white hexagon has three white neighbours. Static topology
    // identifies those edges; the actual curve always comes from this frame.
    lda face_ptr
    sec
    sbc #<football_faces
    lsr
    clc
    adc raster_edge_index
    tax
    lda shared_topology_ids,x
    cmp #255
    bne !shared+
    jmp raster_edge_uncached_active
!shared:
    tax
    jsr shared_edge_lookup
    bcc !generate+
    rts
!generate:
    ldx raster_dy
    lda ratio_row_lo,x
    sta raster_ratio_ptr
    lda ratio_row_hi,x
    clc
    adc #>ratio_q
    sta raster_ratio_ptr+1
    ldy raster_dx
    lda (raster_ratio_ptr),y
    sta raster_q
    asl
    sta raster_q2
    clc
    adc raster_q
    sta raster_q3
    lda ratio_row_hi,x
    clc
    adc #>ratio_r
    sta raster_ratio_ptr+1
    lda (raster_ratio_ptr),y
    sta raster_r
    asl
    sta raster_r2
    clc
    adc raster_r
    sta raster_r3
    lda raster_x0
    sta raster_x
    lda #0
    sta raster_error
    ldx raster_edge_first
    lda sample_y,x
    sec
    sbc raster_y0
    beq !sample+
    jsr raster_advance
!sample:
    lda raster_x
    ldx raster_negative
    bne !ceil_ready+
    ldx raster_error
    beq !ceil_ready+
    clc
    adc #1
!ceil_ready:
    // Cache the absolute crossing generated by this edge's live rational DDA.
    ldy shared_cache_position
    sta (shared_cache_ptr),y
    inc shared_cache_position
    ldx raster_edge_sample
    cmp span_left,x
    bcs !not_left+
    sta span_left,x
!not_left:
    cmp span_right,x
    bcc !not_right+
    sta span_right,x
!not_right:
    lda sample_gap,x
    inc raster_edge_sample
    ldx raster_edge_sample
    cpx raster_edge_end
    bcc !advance+
    rts
!advance:
    jsr raster_advance
    jmp !sample-


shared_generation: .byte 0
shared_cache_ready: .byte 0
shared_curve_pointer_lo:
    .fill SHARED_CACHE_SLOTS, <(SHARED_CURVES+i*SHARED_CURVE_LENGTH)
shared_curve_pointer_hi:
    .fill SHARED_CACHE_SLOTS, >(SHARED_CURVES+i*SHARED_CURVE_LENGTH)
shared_topology_ids:
    .byte 255,0,255,1,255,2,2,255,3,255,4,255
    .byte 255,5,255,6,255,7,7,255,8,255,0,255
    .byte 255,4,255,9,255,5,10,255,11,255,12,255
    .byte 255,13,255,14,255,10,15,255,6,255,16,255
    .byte 255,12,255,17,255,15,16,255,18,255,13,255
    .byte 19,255,20,255,21,255,255,1,255,22,255,19
    .byte 21,255,23,255,3,255,255,24,255,20,255,25
    .byte 25,255,26,255,11,255,255,14,255,27,255,24
    .byte 255,17,255,28,255,8,22,255,28,255,26,255
    .byte 9,255,29,255,18,255,255,27,255,29,255,23

.assert "Shared-edge helpers must remain below I/O", * <= $d000, true
