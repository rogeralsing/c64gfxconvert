'use strict';

// Separate ten-buffer experiment. The source movie, font and fast player remain
// unchanged; only their load addresses and the screen presentation change.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const {spawnSync} = require('node:child_process');
const {compilePlayback} = require('./build-scene-player.cjs');

const here = __dirname;
const FONT = 0x4000, SOURCE = 0x8000, LIMIT = 0xd000;
const SCREENS = Array.from({length: 10}, (_, i) => 0x4800 + i * 1024);
const LOCKED_FONT_SHA = '1560bd74d24feb0684505f714c5b3e2854b352306efde79b89621ef959e629b1';
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');

// Independent behavioral proof: execute the assembled code against the existing
// reference film, with an old image left in every reused ring slot. The source
// film and reference are inputs, never generated by the code under test.
const HOST_PROOF = String.raw`import hashlib, json, pathlib, statistics, sys
sys.path.insert(0, '/tmp/disco-sid-analysis-py65')
from py65.devices.mpu6502 import MPU

root = pathlib.Path(sys.argv[1])
build = json.loads((root / 'build.json').read_text())
labels = json.loads((root / 'labels.json').read_text())
program = (root / 'player.prg').read_bytes()
reference = (root / 'reference.frames').read_bytes()
font = (root / 'font.bin').read_bytes()
movie = (root / 'movie.bin').read_bytes()
edges = json.loads((root / 'literal-index.json').read_text())
memory = [0xa5] * 65536
load = int.from_bytes(program[:2], 'little')
memory[load:load + len(program) - 2] = program[2:]
screens = build['addresses']['screens']
for screen in screens:
    memory[screen:screen + 1024] = bytes(1024)
cpu = MPU(memory=memory)

def run_to(label, limit=100000):
    endpoint = labels[label]
    start = cpu.processorCycles
    for _ in range(limit):
        if cpu.pc == endpoint:
            return cpu.processorCycles - start
        cpu.step()
    raise AssertionError('Did not reach ' + label + ' from code, pc=' + hex(cpu.pc))

def stats(values):
    return dict(min=min(values), mean=statistics.mean(values), max=max(values))

records = []
front = 0
copy_cycles, render_cycles = [], []
# One entry transition plus three full 96-frame loops exercises every patch,
# all ten buffer addresses, and the independent 96-frame/10-screen wraparound.
sequence = [edges[0]] + edges[1:] * 3
for serial, edge in enumerate(sequence):
    source, target = edge['fromPose'], edge['targetPose']
    assert bytes(memory[screens[front]:screens[front] + 1000]) == reference[source * 1000:(source + 1) * 1000]
    memory[labels['front_index']] = front
    memory[labels['front_screen_hi']] = screens[front] >> 8
    memory[labels['frame_index']] = source
    memory[labels['next_frame']] = target
    # Return from the real slot-selection function directly to copy_start.
    cpu.pc = labels['choose_next_buffer']
    cpu.sp = 0xfd
    return_address = labels['copy_start'] - 1
    memory[0x1fe] = return_address & 255
    memory[0x1ff] = return_address >> 8
    run_to('copy_start')
    back = memory[labels['back_index']]
    assert back == (front + 1) % 10
    assert memory[labels['back_screen_hi']] == screens[back] >> 8
    assert memory[labels['back_end_hi']] == (screens[back] >> 8) + 3
    before = [bytes(memory[screen:screen + 1024]) for screen in screens]
    copied = run_to('copy_end')
    assert bytes(memory[screens[back]:screens[back] + 1024]) == before[front], ('copy', serial)
    for slot, screen in enumerate(screens):
        if slot != back:
            assert bytes(memory[screen:screen + 1024]) == before[slot], ('copy touched other screen', serial, slot)
    run_to('render_start')
    rendered = run_to('render_end')
    actual = bytes(memory[screens[back]:screens[back] + 1024])
    assert actual[:1000] == reference[target * 1000:(target + 1) * 1000], ('delta', serial, source, target)
    assert actual[1000:] == bytes(24), ('spare bytes', serial)
    for slot, screen in enumerate(screens):
        if slot != back:
            assert bytes(memory[screen:screen + 1024]) == before[slot], ('delta touched other screen', serial, slot)
    assert bytes(memory[0x4000:0x4000 + len(font)]) == font, ('font', serial)
    assert bytes(memory[0x8000:0x8000 + len(movie)]) == movie, ('movie', serial)
    assert memory[labels['frame_index']] == source, ('early pose switch', serial)
    copy_cycles.append(copied)
    render_cycles.append(rendered)
    records.append(dict(serial=serial, fromPose=source, targetPose=target, frontIndex=front,
                        backIndex=back, copyCpuCycles=copied, renderCpuCycles=rendered,
                        totalCpuCycles=copied + rendered))
    # Continue at the real flip code, skipping only the raster wait. The decoder
    # itself is unaware of the script, source pose and chosen buffer sequence.
    cpu.pc = labels['held_frame_done']
    run_to('presented')
    assert memory[labels['front_index']] == back
    assert memory[labels['front_screen_hi']] == screens[back] >> 8
    assert memory[labels['frame_index']] == target
    assert memory[0xd018] == 0x20 + back * 16
    front = back

result = dict(passed=True, scope='Assembled 6502 copy, exact delta and ring selection; no VIC timing claims.',
              transitionsVerified=len(records), uniqueTransitionsVerified=len(edges),
              closingTransitionsVerified=sum(1 for r in records if r['fromPose'] == 96),
              bufferCount=10, allSlotsVisited=sorted(set(r['backIndex'] for r in records)),
              sourceAndFontUnchanged=True, frontUnchangedDuringRender=True,
              copyBytesPerFrame=1024, visibleCharactersPerFrame=1000,
              copyCpuCycles=stats(copy_cycles), renderCpuCycles=stats(render_cycles),
              totalCpuCycles=stats([c + r for c, r in zip(copy_cycles, render_cycles)]),
              programSha256=hashlib.sha256(program).hexdigest(), records=records)
(root / 'host-proof.json').write_text(json.dumps(result, indent=2) + '\n')
print(json.dumps({k:v for k,v in result.items() if k != 'records'}, indent=2))
`;

function main(argv = process.argv.slice(2)) {
  const option = (name, fallback) => {
    const inline = argv.find(value => value.startsWith(`--${name}=`));
    if (inline) return inline.slice(name.length + 3);
    const index = argv.indexOf(`--${name}`);
    return index >= 0 ? argv[index + 1] : fallback;
  };
  const input = path.resolve(option('input', path.join(here, 'build/three-scene-flagship-star-pal/storage')));
  const root = path.resolve(option('output', path.join(here, 'build/three-scene-flagship-star-ring')));
  const output = path.join(root, 'ring-10');
  const scriptPath = path.resolve(option('script', path.join(input, '../characters/playback.json')));
  const study = JSON.parse(fs.readFileSync(path.join(input, 'study.json')));
  const metadata = study.sourceMetadata || {};
  const reference = fs.readFileSync(path.join(input, 'reference.frames'));
  const font = fs.readFileSync(path.join(input, 'font.bin'));
  const movie = fs.readFileSync(path.join(input, 'literal.bin'));
  const index = JSON.parse(fs.readFileSync(path.join(input, 'literal-index.json')));
  const count = study.frameCount;
  assert(count > 1 && count < 256 && study.loop, 'This exact-loop experiment needs a looping film of 2..255 frames.');
  assert.equal(study.fps, 25);
  assert.equal(font.length, 2048);
  assert.equal(sha(font), LOCKED_FONT_SHA, 'The locked font must remain unchanged.');
  assert.equal(sha(font), study.hashes.font);
  assert.equal(reference.length, count * 1000);
  assert(reference.subarray(0, 1000).every(code => code === 0));
  assert.equal(sha(reference), study.hashes.reference);
  assert.equal(sha(movie), study.formats.literal.sourceSha256);
  assert(movie.length <= LIMIT - SOURCE, 'The complete unchanged film must fit at $8000..$cfff.');
  assert.equal(index.length, count);
  const playback = compilePlayback(JSON.parse(fs.readFileSync(scriptPath)), index, count, study.fps);
  const pointers = Buffer.alloc(count * 2);
  let offset = 0;
  index.forEach((record, frame) => {
    assert.equal(record.fromPose, frame);
    assert.equal(record.targetPose, frame === count - 1 ? study.loop.startFrame : frame + 1);
    assert.equal(record.offset, offset, 'Patches must cover the input movie contiguously.');
    assert(Number.isInteger(record.bytes) && record.bytes > 0);
    pointers.writeUInt16LE(SOURCE + record.offset, frame * 2);
    offset += record.bytes;
  });
  assert.equal(offset, movie.length);
  fs.mkdirSync(output, {recursive: true});
  for (const [name, bytes] of Object.entries({
    'font.bin': font, 'movie.bin': movie, 'pointers.bin': pointers,
    'reference.frames': reference, 'playback.bin': playback.bytecode
  })) fs.writeFileSync(path.join(output, name), bytes);
  fs.writeFileSync(path.join(output, 'literal-index.json'), JSON.stringify(index, null, 2) + '\n');
  fs.writeFileSync(path.join(output, 'playback.json'), JSON.stringify(playback.commands, null, 2) + '\n');
  const playbackMetadata = {...playback, source: scriptPath};
  delete playbackMetadata.bytecode;
  fs.writeFileSync(path.join(output, 'playback-metadata.json'), JSON.stringify(playbackMetadata, null, 2) + '\n');
  fs.writeFileSync(path.join(output, 'main.asm'), [
    `.const PREVIEW_FRAME_COUNT = ${count}`,
    '.var fontData = LoadBinary("font.bin")',
    '.var movieData = LoadBinary("movie.bin")',
    '.var pointerData = LoadBinary("pointers.bin")',
    '.var scriptData = LoadBinary("playback.bin")',
    `.import source "${path.relative(output, path.join(here, 'ring-player.asm')).split(path.sep).join('/')}"`, ''
  ].join('\n'));
  const assembler = process.env.KICKASS || '/Users/rogerjohansson/.local/bin/kickass';
  const compiled = spawnSync('rtk', ['proxy', assembler, 'main.asm', '-odir', output,
    '-o', path.join(output, 'player.prg'), '-symbolfile', '-vicesymbols'], {cwd: output, stdio: 'inherit'});
  assert.equal(compiled.status, 0, 'KickAssembler failed.');
  const program = fs.readFileSync(path.join(output, 'player.prg'));
  const labels = Object.fromEntries([...fs.readFileSync(path.join(output, 'main.sym'), 'utf8')
    .matchAll(/\.label\s+(\w+)\s*=\s*\$([0-9a-fA-F]+)/g)]
    .map(match => [match[1], parseInt(match[2], 16)]));
  assert(labels.player_code_end <= 0x2000);
  assert.equal(labels.font, FONT);
  assert.equal(labels.animation, SOURCE);
  assert.equal(labels.animation_end, SOURCE + movie.length);
  const loadAddress = program.readUInt16LE(0);
  index.forEach((record, frame) => {
    const address = pointers.readUInt16LE(frame * 2);
    const actual = program.subarray(2 + address - loadAddress, 2 + address - loadAddress + record.bytes);
    assert(actual.equals(movie.subarray(record.offset, record.offset + record.bytes)), `Assembled patch ${frame} changed.`);
  });
  assert(program.subarray(2 + FONT - loadAddress, 2 + FONT - loadAddress + font.length).equals(font));
  const codeRegionBytes = labels.player_code_end - 0x1000;
  const codeStateBytes = codeRegionBytes - pointers.length - playback.bytecodeBytes;
  // BASIC line (10 bytes) plus its final two-byte zero line pointer.
  const basicBytes = 12;
  const meaningfulLoadedBytes = codeRegionBytes + font.length + movie.length + basicBytes;
  const result = {
    name: 'ring-10', variant: 'ring-10', dataset: metadata.name || 'flagship-six-point-star',
    codec: 'global varint skip/length with raw literal characters', sparse: false, hidden: true,
    settings: metadata.settings || {}, bufferCount: SCREENS.length,
    storedFrames: count, storedTransitions: index.length, firstSourcePose: 0,
    sourcePoseIndices: Array.from({length: count}, (_, frame) => frame),
    nominalFps: 25, nativeFps: null, minimumFieldsPerImage: 2,
    fieldsPerImage: null, presentationTiming: 'At least two PAL fields. Copy and delta run after the first complete field; flip only at the next line-256 boundary. Extra fields are allowed if work overruns.',
    checkpoints: {
      presented: 'Just after D018 changes; scanout still belongs to the old field.',
      frame_done: 'First complete visible field of frame_index; frame_counter has incremented.',
      copy_start: 'Old frame_index/front selected, next_frame is target; copy into next ring slot.',
      copy_end: 'All 1024 bytes copied, before any delta stores.',
      render_start: 'Before patch-pointer load and exact delta decode into back buffer.',
      render_end: 'Target screen complete; old frame_index/front still selected.',
      held_frame_done: 'After next boundary, immediately before flip; old screen and pose still selected.'
    },
    nominalDurationSeconds: playback.nominalSeconds, uniqueFrameSeconds: count / 25,
    totalDisplayedFrames: playback.totalDisplayedFrames, finiteClip: !playback.repeatsForever,
    introSeconds: study.introSeconds, loop: study.loop, playback: playbackMetadata,
    abi: 'Repeat skip LEB128, literalLength LEB128, literal bytes until screen position 1000. Before every patch, copy all 1024 bytes from displayed front to the next ring screen.',
    closingPatchIncluded: true, introPayloadBytes: study.formats.literal.introPayloadBytes,
    loopPayloadBytes: study.formats.literal.loopPayloadBytes, closingPatchBytes: study.formats.literal.closingPatchBytes,
    dataArenaBytes: LIMIT - SOURCE, payloadBytes: movie.length, unusedArenaBytes: LIMIT - SOURCE - movie.length,
    sourceRegions: [{start: SOURCE, end: SOURCE + movie.length, file: 'movie.bin', sha256: sha(movie)}],
    sourcePatches: index.map((record, frame) => ({frame, offset: record.offset, bytes: record.bytes, address: pointers.readUInt16LE(frame * 2)})),
    fontBytes: font.length, seedScreenBytes: 0, pointerBytes: pointers.length,
    codeStateBytes, codeStateAndPointersBytes: codeStateBytes + pointers.length, codeRegionBytes,
    playbackBytecodeBytes: playback.bytecodeBytes, workScreenBytes: 10240, copyBytesPerFrame: 1024,
    colorRamBytes: 1024, colorRamCells: 1024, zeroPageBytes: 9, basicBytes, programBytes: program.length,
    meaningfulLoadedBytes, addressGapPaddingBytes: program.length - 2 - meaningfulLoadedBytes,
    animationAndFontBytes: pointers.length + font.length + movie.length,
    mainRamBytes: meaningfulLoadedBytes + 10240 + 9,
    usedRamBytes: meaningfulLoadedBytes + 10240 + 1024 + 9,
    memoryAccounting: 'Ten 1024-byte working screens are runtime main RAM, not movie payload. No stored seed screen. Meaningful loaded bytes excludes PRG address-gap padding, working screens, color RAM and zero page. mainRamBytes counts ordinary main RAM; usedRamBytes also includes the separately allocated 1024 Color RAM cells and must not be subtracted from main RAM capacity. Code state includes ring tables; pointers and playback bytecode are counted separately.',
    hashes: {program: sha(program), movie: sha(movie), font: sha(font), reference: sha(reference), playback: sha(playback.bytecode)},
    immutableInputs: {storage: input, playback: scriptPath, lockedFontSha256: LOCKED_FONT_SHA},
    addresses: {code: 0x1000, codeEnd: labels.player_code_end, font: FONT, source: SOURCE,
      sourceEnd: labels.animation_end, front: SCREENS[0], hidden: SCREENS[1], initialScreen: null,
      screens: SCREENS, screenEnd: SCREENS.at(-1) + 1024, vicBank: 0x4000,
      cia2BankBits: 2, d018Values: SCREENS.map((_, i) => 0x20 + i * 16), zeroPageStart: 2, zeroPageEnd: 11}
  };
  fs.writeFileSync(path.join(output, 'build.json'), JSON.stringify(result, null, 2) + '\n');
  fs.writeFileSync(path.join(output, 'labels.json'), JSON.stringify(labels, null, 2) + '\n');
  fs.writeFileSync(path.join(output, 'host-proof.py'), HOST_PROOF);
  const proof = spawnSync('rtk', ['proxy', 'python3', path.join(output, 'host-proof.py'), output], {cwd: output, stdio: 'inherit'});
  assert.equal(proof.status, 0, 'Assembled-code host proof failed.');
  console.log(JSON.stringify({output, programSha256: result.hashes.program,
    payloadBytes: result.payloadBytes, workScreenBytes: result.workScreenBytes,
    pointerBytes: result.pointerBytes, codeRegionBytes, meaningfulLoadedBytes, usedRamBytes: result.usedRamBytes}, null, 2));
  return result;
}

module.exports = {main};
if (require.main === module) main();
