#!/usr/bin/env python3
"""Retain the exact True Paint MCI fields used by the third demo part."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path


PART = Path(__file__).resolve().parents[1]
REPOSITORY = PART.parent
ASSETS = PART / "assets"
SOURCE = REPOSITORY / "images/giana-man.mci"
PROJECT = REPOSITORY / "images/giana-man.json"
SPANS = {
    "screen-a": (2, 1002),
    "bitmap-a": (1026, 9026),
    "bitmap-b": (9218, 17218),
    "screen-b": (17410, 18410),
    "colors": (18434, 19434),
    "background": (1002, 1003),
}


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def preview(source: bytes) -> None:
    try:
        from PIL import Image
    except ImportError:
        return
    palette = [tuple(int(value, 16) for value in line.split()[:3])
               for line in (ASSETS / "peptoette-a.vpl").read_text().splitlines()
               if line.strip() and not line.lstrip().startswith("#")]
    frames = []
    for phase in range(2):
        screen_offset, bitmap_offset = ((2, 1026), (17410, 9218))[phase]
        frame = Image.new("RGB", (320, 200), palette[source[1002]])
        for y in range(200):
            for x in range(160):
                cell = y // 8 * 40 + x // 4
                screen = source[screen_offset + cell]
                colors = (source[1002], screen >> 4, screen & 15, source[18434 + cell])
                packed = source[bitmap_offset + cell * 8 + y % 8]
                color = palette[colors[packed >> (6 - 2 * (x % 4)) & 3]]
                for column in (x * 2 + phase, x * 2 + phase + 1):
                    if column < 320:
                        frame.putpixel((column, y), color)
        frames.append(frame)
        frame.save(ASSETS / f"mci-phase-{phase}.png")
    Image.blend(frames[0], frames[1], 0.5).save(ASSETS / "mci-preview.png")


def main() -> None:
    source = SOURCE.read_bytes()
    project_bytes = PROJECT.read_bytes()
    project = json.loads(project_bytes)
    if len(source) != 19434 or source[:2] != b"\x00\x9c":
        raise ValueError("Expected the uncompressed 19,434-byte True Paint MCI at $9C00")
    if source[1002] > 15 or any(color > 15 for color in source[18434:19434]):
        raise ValueError("MCI background and shared colors must use C64 indices 0..15")
    image = project.get("image", {})
    if image.get("graphicsMode") != "mci" or image.get("backgroundColorIndex") != source[1002]:
        raise ValueError("The authoring project must describe the supplied MCI and its background")
    if image.get("paletteId") != "peptoette-a":
        raise ValueError("Native review targets the project's peptoette-a palette")
    ASSETS.mkdir(parents=True, exist_ok=True)
    (ASSETS / "giana-man.mci").write_bytes(source)
    components = {}
    for name, (first, end) in SPANS.items():
        data = source[first:end]
        path = f"mci-{name}.bin"
        (ASSETS / path).write_bytes(data)
        components[name] = {"path": f"assets/{path}", "source_offset": first,
                            "bytes": len(data), "sha256": digest(data)}
    (ASSETS / "mci.asm").write_text(
        "// Generated by tools/prepare-mci.py. Graphics arrive in the next disk jobs.\n"
        f".const MCI_BACKGROUND = {source[1002]}\n"
        ".const MCI_SCREEN_A = $0400\n.const MCI_BITMAP_A = $2000\n"
        ".const MCI_SCREEN_B = $8400\n.const MCI_BITMAP_B = $a000\n"
        ".const MCI_COLOR_SOURCE = $c000\n")
    receipt = {
        "format": "giana-third-part-truepaint-mci-v1",
        "source": {"path": str(SOURCE.relative_to(REPOSITORY)), "bytes": len(source),
                   "sha256": digest(source), "load_address": 0x9c00},
        "project": {"path": str(PROJECT.relative_to(REPOSITORY)), "sha256": digest(project_bytes),
                    "graphics_mode": image["graphicsMode"], "palette_id": image["paletteId"]},
        "components": components,
        "display": {"width": 320, "height": 200, "fields": 2,
                    "field_b_offset_physical_pixels": 1,
                    "field_change_raster": 256, "field_rate": "one per PAL frame",
                    "background": source[1002]},
        "memory": {"screen_a": 0x0400, "bitmap_a": 0x2000,
                   "screen_b": 0x8400, "bitmap_b": 0xa000,
                   "color_source": 0xc000, "color_ram": 0xd800,
                   "vic_memory_pointer": 0x18, "cia2_direction_values": [0x3c, 0x3e],
                   "scroll_values": [0x18, 0x19]},
        "preservation": {"source_files_modified": False, "mci_copy_is_exact": True,
                         "pixel_or_palette_conversion": False, "phase_bytes_preserved": True,
                         "json_embedded_images_not_imported": True},
    }
    (ASSETS / "mci-import.json").write_text(json.dumps(receipt, indent=2) + "\n")
    preview(source)
    print(f"MCI part: exact {len(source):,}-byte source; 19,000 graphics bytes; background {source[1002]}.")
    print(f"Source SHA-256: {digest(source)}")


if __name__ == "__main__":
    main()
