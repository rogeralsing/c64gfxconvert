#!/usr/bin/env python3
"""Import giana7 and its game/light masks for the second room."""

from __future__ import annotations

import hashlib
import importlib.util
import json
from pathlib import Path


PART = Path(__file__).resolve().parents[1]
REPOSITORY = PART.parent
ASSETS = PART / "assets"
SOURCE_KOALA = REPOSITORY / "images/giana7.koa"
SOURCE_PROJECT = REPOSITORY / "images/giana7.json"


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def pack_backward(data: bytes) -> bytes:
    """Suffix tags allow a small decoder to consume the stream from its end."""
    packed = bytearray()
    position = 0
    while position < len(data):
        start = position
        position += 1
        while position < len(data) and data[position] == data[start] and position - start < 128:
            position += 1
        count = position - start
        if count >= 3:
            packed.extend((data[start], 0x80 | (count - 1)))
            continue
        position = start
        while position < len(data) and position - start < 128:
            if position + 2 < len(data) and data[position] == data[position + 1] == data[position + 2]:
                break
            position += 1
        count = position - start
        assert 1 <= count <= 128
        packed.extend(data[start:position])
        packed.append(count - 1)
    return bytes(packed)


def unpack_backward(packed: bytes, size: int) -> bytes:
    source = len(packed)
    destination = size
    output = bytearray(size)
    while source:
        source -= 1
        tag = packed[source]
        count = (tag & 0x7f) + 1
        assert count <= destination
        destination -= count
        if tag & 0x80:
            assert source >= 1
            source -= 1
            output[destination:destination + count] = bytes((packed[source],)) * count
        else:
            assert source >= count
            source -= count
            output[destination:destination + count] = packed[source:source + count]
    assert destination == 0
    return bytes(output)


def marker_summary(project: dict) -> list[dict]:
    summaries = []
    for layer in project["layers"]:
        if layer.get("type") != "tile-markers":
            continue
        mask = layer["markers"]["tiles"]
        if len(mask) != 1000 or any(type(value) is not int or value not in (0, 1) for value in mask):
            raise ValueError(f"Invalid tile marker mask: {layer.get('name')}")
        cells = [cell for cell, value in enumerate(mask) if value]
        summaries.append({"name": layer["name"], "visible": layer.get("visible", True),
                          "count": len(cells), "cells": cells,
                          "bounds": [min(cell % 40 for cell in cells), min(cell // 40 for cell in cells),
                                     max(cell % 40 for cell in cells), max(cell // 40 for cell in cells)]
                          if cells else None})
    return summaries


def scene_helpers():
    spec = importlib.util.spec_from_file_location("giana_scene_import", PART / "tools/prepare-scene.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def prepare_lighting(koala: bytes, project: dict) -> dict:
    scene = scene_helpers()
    game = scene.marker(project, "GameArea")
    light = scene.marker(project, "ScreenLight")
    expected_game = [row * 40 + column for row in range(3, 11) for column in range(23, 33)]
    if game["cells"] != expected_game:
        raise ValueError("giana7 GameArea must match the existing 10x8 TV rectangle at column23, row3")
    if set(game["cells"]) & set(light["cells"]):
        raise ValueError("giana7 ScreenLight and GameArea must not overlap")
    cells = light["cells"]
    count = len(cells)
    tile_major = scene.illumination_table(koala, cells)
    screen, color = tile_major[:count * 3], tile_major[count * 3:]
    phase_major = bytes(screen[cell * 3 + phase] for phase in range(3) for cell in range(count)) + \
                  bytes(color[cell * 3 + phase] for phase in range(3) for cell in range(count))
    addresses = [0x0400 + cell for cell in cells]
    data = bytes(address & 255 for address in addresses) + bytes(address >> 8 for address in addresses) + phase_major
    assert len(data) == count * 8
    (ASSETS / "scene7-lighting.bin").write_bytes(data)
    assembly = ["// Generated by tools/prepare-ending.py using prepare-scene.py illumination rules.",
                f".const SCENE7_LIGHT_TILE_COUNT = {count}",
                ".var SCENE7_LIGHT_CELLS = List()",
                *(f".eval SCENE7_LIGHT_CELLS.add({cell})" for cell in cells),
                '.var scene7LightingFile = LoadBinary("scene7-lighting.bin")',
                "scene7LightCellLow:",
                "    .fill SCENE7_LIGHT_TILE_COUNT, scene7LightingFile.get(i)",
                "scene7LightCellHigh:",
                "    .fill SCENE7_LIGHT_TILE_COUNT, scene7LightingFile.get(SCENE7_LIGHT_TILE_COUNT + i)",
                "scene7LightScreen:"]
    for kind, offset in (("Screen", count * 2), ("Color", count * 5)):
        if kind == "Color":
            assembly.append("scene7LightColor:")
        for phase in range(3):
            assembly.extend([f"scene7Light{kind}{phase}:",
                             f"    .fill SCENE7_LIGHT_TILE_COUNT, scene7LightingFile.get({offset + phase * count} + i)"])
    assembly.extend(["scene7LightingEnd:",
                     '.assert "Scene7 light addresses and phases match", scene7LightingEnd - scene7LightCellLow, SCENE7_LIGHT_TILE_COUNT * 8',
                     '.assert "Scene7 lighting avoids sprite helpers", * <= $9000, true', ""])
    (ASSETS / "scene7-lighting.asm").write_text("\n".join(assembly))
    metadata = {"file": "scene7-lighting.bin", "bytes": len(data), "sha256": digest(data),
                "cells": cells, "count": count,
                "layout": "SCREEN=$0400 cell low addresses, high addresses, three screen phases, three Color RAM phases; every section has one byte per light cell",
                "screen_destination_base": 0x0400, "color_destination_high_byte_add": 0xd4,
                "plus_one_map": list(scene.PLUS_ONE), "plus_two_map": list(scene.PLUS_TWO),
                "protected_color_indices": [0, 1, 2, 6, 9, 11],
                "marker_visibility_policy": "Apply the named masks even when their editor layers are hidden, as requested by the user.",
                "game_area": game, "screen_light": light}
    (ASSETS / "scene7-lighting.json").write_text(json.dumps(metadata, indent=2) + "\n")
    return metadata


def preview(koala: bytes) -> None:
    try:
        from PIL import Image
    except ImportError:
        return
    palette = [tuple(int(value, 16) for value in line.split()[:3])
               for line in (ASSETS / "peptoette-a.vpl").read_text().splitlines()
               if line.strip() and not line.lstrip().startswith("#")]
    image = Image.new("RGB", (320, 200))
    pixels = image.load()
    for y in range(200):
        for x in range(160):
            cell = y // 8 * 40 + x // 4
            code = koala[2 + cell * 8 + y % 8] >> (6 - 2 * (x % 4)) & 3
            screen = koala[8002 + cell]
            color = (koala[-1] & 15, screen >> 4, screen & 15, koala[9002 + cell] & 15)[code]
            pixels[x * 2, y] = pixels[x * 2 + 1, y] = palette[color]
    image.save(ASSETS / "ending-preview.png")


def main() -> None:
    koala = SOURCE_KOALA.read_bytes()
    project_bytes = SOURCE_PROJECT.read_bytes()
    project = json.loads(project_bytes)
    if len(koala) != 10003:
        raise ValueError("giana7.koa must be a standard 10,003-byte Koala file")
    if project["image"]["graphicsMode"] != "bitmap" or project["image"]["paletteId"] != "peptoette-a":
        raise ValueError("giana7 must use bitmap mode and the peptoette-a palette")
    background = koala[10002]
    if background > 15 or project["image"]["backgroundColorIndex"] != background:
        raise ValueError("Koala and project background colors disagree")
    colors = koala[9002:10002]
    if any(value > 15 for value in colors):
        raise ValueError("Color RAM nibble packing requires zero source high nibbles")
    packed_colors = bytes(colors[index] << 4 | colors[index + 1] for index in range(0, 1000, 2))
    data = koala[2:9002] + packed_colors
    packed = pack_backward(data)
    if len(packed) > 8186:
        raise ValueError(f"Packed room needs {len(packed)} bytes; KERNAL RAM reserves six bytes for NMI/reset/IRQ vectors")
    unpacked = unpack_backward(packed, 9500)
    assert unpacked == data
    expanded_colors = bytes(value for pair in unpacked[9000:] for value in (pair >> 4, pair & 15))
    assert unpacked[:9000] + expanded_colors == koala[2:10002]
    ASSETS.mkdir(parents=True, exist_ok=True)
    (ASSETS / "giana7.koa").write_bytes(koala)
    (ASSETS / "ending-packbits.bin").write_bytes(packed)
    (ASSETS / "ending.asm").write_text(
        '// Generated by tools/prepare-ending.py; packed source lives below KERNAL ROM.\n'
        f'.const ENDING_BACKGROUND = {background}\n'
        f'.const ENDING_PACKED_BYTES = {len(packed)}\n'
        '.const ENDING_UNPACKED_BYTES = 9500\n'
        '.const ENDING_COLOR_PACKED_BYTES = 500\n'
        'endingPacked:\n'
        '    .import binary "ending-packbits.bin"\n'
        'endingPackedEnd:\n'
        '.assert "Ending packed size matches", endingPackedEnd - endingPacked, ENDING_PACKED_BYTES\n'
        '.assert "Ending packed image avoids hardware vectors", * <= $fffa, true\n'
    )
    lighting = prepare_lighting(koala, project)
    metadata = {
        "format": "c64-giana-room-v2",
        "sources": {
            "koala": {"path": "images/giana7.koa", "bytes": len(koala), "sha256": digest(koala),
                      "load_address": int.from_bytes(koala[:2], "little")},
            "project": {"path": "images/giana7.json", "sha256": digest(project_bytes)},
        },
        "image": {"width_physical": 320, "height": 200, "palette": "peptoette-a",
                  "background": background, "bitmap_bytes": 8000, "screen_bytes": 1000,
                  "color_bytes": 1000},
        "markers": marker_summary(project),
        "marker_policy": "GameArea and ScreenLight are runtime masks even though both layers are hidden in the editor. Preserve source pixels outside the game and marked illumination cells.",
        "lighting": lighting,
        "packing": {"file": "ending-packbits.bin", "bytes": len(packed), "sha256": digest(packed),
                    "unpacked_bytes": len(data), "unpacked_sha256": digest(data),
                    "source_layout": "bitmap[8000], screen[1000], packed Color RAM[500]; first cell high nibble, second cell low nibble; background is an assembly constant",
                    "expanded_image_bytes": 10000, "color_nibble_packing_lossless": True,
                    "format": "Backward suffix-tag PackBits. Literal: data then tag0..127; repeat: value then tag128..255. Count=(tag&127)+1. Runs>=3, packet length<=128.",
                    "roundtrip_verified": True},
        "component_sha256": {name: digest(koala[2 + start:2 + end]) for name, start, end in
                             (("bitmap", 0, 8000), ("screen", 8000, 9000), ("color", 9000, 10000))},
        "preservation": {"source_files_modified": False, "asset_is_exact_koala_copy": True,
                         "palette_conversion": False, "bitmap_modified": False},
    }
    (ASSETS / "ending-import.json").write_text(json.dumps(metadata, indent=2) + "\n")
    preview(koala)
    print(f"Room giana7: 10,000 image bytes nibble-packed to 9,500, then {len(packed)} PackBits bytes; background {background}.")
    print(f"Room lighting: {lighting['count']} cells, {lighting['bytes']} bytes including cell addresses.")
    print(f"Packed SHA-256: {digest(packed)}")


if __name__ == "__main__":
    main()
