// An independent WAV trial using the canonical SID3 sample-and-hold primitive.
// The foreground expands packed four-bit values. The sample interrupt reads
// ordinary unsigned bytes and retains the existing 126-cycle SID transfer.
.import source "config.asm"
.label buffer_a = $0200
.label buffer_b = $0300
.label boundary_count = $02
.label boundary_before = $03
.label generated_pages = $04
.label underruns = $05
.label finished = $06
.label next_buffer = $07
.label target_buffer = $08
.label nmi_entry = $dc04
BasicUpstart2(start)
start:
    sei
    cld
    ldx #$ff
    txs
    lda #$7f
    sta $dc0d
    sta $dd0d
    lda $dc0d
    lda $dd0d
    lda #0
    sta $dc0e
    sta $dc0f
    sta $dd0e
    sta $dd0f
    sta $d011
    sta $d015
    sta $d01a
    lda #$ff
    sta $d019
    lda #$35
    sta $01
    lda #0
    ldx #24
!sid_clear:
    sta $d400,x
    dex
    bpl !sid_clear-
    ldx #6
!state_clear:
    sta $02,x
    dex
    bpl !state_clear-
    ldx #0
!copy_nmi:
    lda nmi_image,x
    sta $80,x
    inx
    cpx #(nmi_end-nmi_common)
    bne !copy_nmi-
    lda #$40
    sta $dd0c
    lda #<nmi_entry
    sta $fffa
    lda #>nmi_entry
    sta $fffb
    lda #$4c
    sta $dc04
    lda #<PACKED_START
    sta packed_read+1
    lda #>PACKED_START
    sta packed_read+2
    lda #>buffer_a
    sta target_buffer
    jsr fill_page
    lda #>buffer_b
    sta target_buffer
    jsr fill_page
    lda #>buffer_b
    sta next_buffer
    lda #0
    sta $d413
    lda #$f0
    sta $d414
    lda #1
    sta $d412
    lda #15
    sta $d418
    // Prime the same neutral held voltage and envelope as the native mixer.
    lda #128
    sta $d40f
    lda #9
    sta $d412
    lda #1
    sta $d412
    .fill 47,$ea
    lda #17
    sta $d412
    lda #1
    sta $d412
    lda #0
    sta $d40f
    ldy #32
!warm_outer:
    ldx #0
!warm_inner:
    dex
    bne !warm_inner-
    dey
    bne !warm_outer-
    lda #0
    sta $dc05
    lda #125
    sta $dc06
    lda #0
    sta $dc07
    lda #125
    sta $dd04
    lda #0
    sta $dd05
    lda #$81
    sta $dd0d
    // Starting near an even rasterline keeps sample transfers off badlines.
    lda #$fe
!raster_wait:
    cmp $d012
    bne !raster_wait-
    lda #$11
sample_clock_start:
    sta $dd0e
    sta $dc0f
wait_boundary:
    lda finished
    bne playback_done
    lda boundary_count
    cmp boundary_before
    beq wait_boundary
    sta boundary_before
    lda generated_pages
    cmp #PAGE_COUNT
    beq wait_boundary
    lda next_buffer
    sta target_buffer
    jsr fill_page
    lda boundary_count
    cmp boundary_before
    beq wait_boundary
    inc underruns
    jmp wait_boundary
playback_done:
    lda #0
    sta $d40f
    lda #$09
    sta $d412
done:
    jmp done

fill_page:
    lda target_buffer
    sta decoded_high+2
    sta decoded_low+2
    ldy #0
!decode:
packed_read:
    lda PACKED_START
    tax
    lda high_lookup,x
decoded_high:
    sta buffer_a,y
    iny
    lda low_lookup,x
decoded_low:
    sta buffer_a,y
    iny
    inc packed_read+1
    bne !source_ready+
    inc packed_read+2
    jsr advance_source_page
!source_ready:
    cpy #0
    bne !decode-
    inc generated_pages
producer_done:
    rts

// Every exceptional physical page transition is generated by the packer.
.import source "source-transitions.asm"
nmi_image:
.pseudopc $80 {
nmi_common:
first_latch:
    lda #$11
    sta $d412
    lda #$01
    sta $d412
    lda #$09
    sta $d412
buffer_read:
    lda buffer_a
    sta $d40f
    lda #$01
    sta $d412
sample_dispatch:
    jmp count_sample
count_sample:
    .byte $e6,<(buffer_read+1)
    bne nmi_return
consumer_activate:
    lda next_buffer
    .byte $85,<(buffer_read+2)
    eor #1
    sta next_buffer
    inc boundary_count
    lda boundary_count
    cmp #FULL_PAGES
    bne nmi_return
    lda #<count_final
    .byte $85,<(sample_dispatch+1)
    jmp nmi_return
count_final:
    .byte $e6,<(buffer_read+1)
    .byte $a5,<(buffer_read+1)
    cmp #FINAL_VALUES
    bne nmi_return
    lda #<emit_final
    .byte $85,<(sample_dispatch+1)
    jmp nmi_return
emit_final:
    // The last source value was emitted by this interrupt. The neutral guard
    // is prepared now, and one more whole sample period remains before stop.
    lda #<stop_sampling
    .byte $85,<(sample_dispatch+1)
    jmp nmi_return
stop_sampling:
    lda #0
    sta $dd0e
    sta $dc0f
    lda #$7f
    sta $dd0d
    lda $dd0d
    lda #1
    sta finished
nmi_return:
restore_a:
    lda #0
    jmp $dd0c
nmi_end:
}
.assert "The sample handler must fit its zero-page arena",nmi_end<=$100,true
.assert "The standalone runtime must fit below lookup tables",*<=$0c00,true
.import source "data.asm"
