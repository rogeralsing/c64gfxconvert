"""Observable MOD replay contracts from ProTracker 2.3D's effect routines.

Small pattern fixtures exercise the same public reader/timeline entry points as
conversion. Expected events are literal replay contracts, not generated by the
implementation being checked.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from mod_reader import load_mod
from timeline import build_timeline


def note(sample=0, period=0, effect=0, param=0):
    return dict(sample=sample, period=period, effect=effect, param=param)


def module(rows, finetune=0):
    samples = [dict(id=i, length=4096 if i <= 2 else 0,
                    data=bytes(4096) if i <= 2 else b"", finetune=finetune if i == 1 else 0,
                    volume=32 if i == 1 else 48, loop_start=0, loop_length=2)
               for i in range(1, 32)]
    pattern = [[note() for _ in range(4)] for _ in range(64)]
    for row, values in enumerate(rows):
        for channel, value in enumerate(values):
            pattern[row][channel] = value
    pattern[len(rows)][3] = note(effect=0xF)
    return dict(samples=samples, patterns=[pattern], orders=[0])


def binary_module(signature=b"M.K."):
    binary = bytearray(1084 + 1024 + 4)
    binary[42:44] = (2).to_bytes(2, "big")
    binary[45] = 32
    binary[950] = 1
    binary[1080:1084] = signature
    binary[1084:1088] = bytes([1, 0xAC, 0x10, 0])
    return binary


class TrackerEffects(unittest.TestCase):
    def test_finetune_uses_the_period_table_without_changing_note_identity(self):
        result = build_timeline(module([[note(1, 428)]], finetune=1))
        self.assertEqual(result["ticks"][0]["channels"][0]["period"], 425)
        self.assertTrue(result["ticks"][0]["channels"][0]["trigger"])

    def test_offset_memory_applies_before_trigger_and_carries_to_later_notes(self):
        result = build_timeline(module([[note(1, 428, 9, 1)],
                                        [note(0, 428, 9, 0)],
                                        [note(1, 428, 9, 0)]]))
        starts = [tick["channels"][0]["offset"] for tick in result["ticks"]
                  if tick["channels"][0]["trigger"]]
        self.assertEqual(starts, [256, 768, 256])

    def test_invalid_offset_shortens_only_the_trigger_that_observes_it(self):
        result = build_timeline(module([[note(1, 428, 9, 8)],
                                        [note(0, 428)], [note(1, 428, 9, 255)]]))
        states = [tick["channels"][0] for tick in result["ticks"] if tick["channels"][0]["trigger"]]
        self.assertEqual([state["offset"] for state in states], [2048, 2048, 0])
        self.assertNotIn("first_segment_bytes", states[0])
        self.assertEqual(states[1]["first_segment_bytes"], 2)
        self.assertEqual(states[2]["first_segment_bytes"], 2)

    def test_tremolo_modulates_output_without_destroying_base_volume(self):
        result = build_timeline(module([[note(1, 428, 7, 0xFF)], [note()]]))
        values = [tick["channels"][0]["volume"] for tick in result["ticks"]]
        self.assertEqual(values[:6], [32, 32, 64, 43, 0, 10])
        self.assertEqual(values[6:12], [32] * 6)

    def test_note_delay_changes_the_playing_sample_only_on_the_due_tick(self):
        result = build_timeline(module([[note(1, 428)], [note(2, 214, 0xE, 0xD3)]]))
        states = [tick["channels"][0] for tick in result["ticks"][6:12]]
        self.assertEqual([state["playing_sample"] for state in states], [1, 1, 1, 2, 2, 2])
        self.assertEqual([state["trigger"] for state in states], [False, False, False, True, False, False])
        self.assertEqual([state["period"] for state in states], [428, 428, 428, 214, 214, 214])

    def test_retrigger_restarts_on_nonzero_ticks_and_on_a_note_free_tick_zero(self):
        result = build_timeline(module([[note(1, 428, 0xE, 0x93)], [note(0, 0, 0xE, 0x93)]]))
        triggers = [i for i, tick in enumerate(result["ticks"][:12]) if tick["channels"][0]["trigger"]]
        self.assertEqual(triggers, [0, 3, 6, 9])

    def test_fine_volume_is_tick_zero_only_and_note_cut_waits_for_its_tick(self):
        result = build_timeline(module([[note(1, 428, 0xE, 0xA2)],
                                        [note(0, 0, 0xE, 0xB3)],
                                        [note(0, 0, 0xE, 0xC2)]]))
        values = [tick["channels"][0]["volume"] for tick in result["ticks"][:18]]
        self.assertEqual(values, [34] * 6 + [31] * 6 + [31, 31, 0, 0, 0, 0])

    def test_fine_portamento_changes_pitch_once_on_tick_zero(self):
        result = build_timeline(module([[note(1, 428, 0xE, 0x12)]]))
        self.assertEqual([tick["channels"][0]["period"] for tick in result["ticks"][:6]], [426] * 6)

    def test_pattern_loop_executes_its_finite_repeat_count(self):
        result = build_timeline(module([[note(1, 428, 0xE, 0x60)], [note(0, 0, 0xE, 0x62)]]))
        rows = [row["row"] for row in result["rows"]]
        self.assertEqual(rows, [0, 1, 0, 1, 0, 1, 2])
        self.assertEqual(len(result["ticks"]), 37)
        self.assertEqual(result["termination"], "F00")

    def test_pattern_delay_continues_effects_without_reloading_the_note(self):
        result = build_timeline(module([[note(1, 428, 0xE, 0xE2), note(2, 214, 0xA, 1)]]))
        self.assertEqual(len(result["ticks"]), 19)
        self.assertEqual(sum(tick["channels"][0]["trigger"] for tick in result["ticks"]), 1)
        self.assertEqual(result["ticks"][17]["channels"][1]["volume"], 31)

    def test_cia_tempo_change_preserves_the_current_tick_duration(self):
        result = build_timeline(module([[note(1, 428, 0xF, 3), note(effect=0xF, param=100)]]))
        self.assertEqual([tick["bpm"] for tick in result["ticks"]], [125, 100, 100, 100])
        self.assertEqual([tick["duration_s"] for tick in result["ticks"]], [.02, .025, .025, .025])
        self.assertAlmostEqual(result["duration_s"], .095)

    def test_vblank_timing_interprets_high_f_commands_as_speed(self):
        song = module([[note(1, 428, 0xF, 48)]])
        song["timing_mode"] = "vblank"
        result = build_timeline(song)
        self.assertEqual(len(result["ticks"]), 49)
        self.assertEqual(result["ticks"][0]["speed"], 48)
        self.assertEqual({tick["bpm"] for tick in result["ticks"]}, {125})

    def test_pattern_delay_with_break_skips_the_first_target_row(self):
        song = module([[note(1, 428, 0xE, 0xE2), note(effect=0xD, param=0x31)]])
        second = [[note() for _ in range(4)] for _ in range(64)]
        second[32][3] = note(effect=0xF)
        song["patterns"].append(second)
        song["orders"].append(1)
        result = build_timeline(song)
        self.assertEqual([(row["order"], row["row"]) for row in result["rows"]], [(0, 0), (1, 32)])

    def test_instrument_only_change_updates_loop_without_retriggering(self):
        result = build_timeline(module([[note(1, 428)], [note(2)]]))
        state = result["ticks"][6]["channels"][0]
        self.assertEqual(state["playing_sample"], 1)
        self.assertEqual(state["loop_sample"], 2)
        self.assertFalse(state["trigger"])

    def test_protracker_effect_eight_is_an_audio_no_op(self):
        result = build_timeline(module([[note(1, 428)], [note(0, 0, 8, 0x25)]]))
        states = [tick["channels"][0] for tick in result["ticks"][6:12]]
        self.assertEqual([state["period"] for state in states], [428] * 6)
        self.assertEqual([state["volume"] for state in states], [32] * 6)
        self.assertFalse(any(state["trigger"] for state in states))

    def test_unimplemented_sample_mutation_does_not_silently_pass(self):
        with self.assertRaisesRegex(ValueError, "Unsupported ProTracker effect EF1"):
            build_timeline(module([[note(1, 428, 0xE, 0xF1)]]))

    def test_flt4_accepts_pcm_but_rejects_external_instrument_references(self):
        binary = binary_module(b"FLT4")
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / "sample.mod"
            path.write_bytes(binary)
            self.assertEqual(load_mod(path)["format"], "Startrekker FLT4")
            binary[1086] = 0x20
            path.write_bytes(binary)
            with self.assertRaisesRegex(ValueError, "external AM/FM"):
                load_mod(path)

    def test_timing_dialect_is_explicit_and_bound_to_the_source_hash(self):
        binary = binary_module()
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / "sample.mod"
            path.write_bytes(binary)
            receipt = path.with_suffix(".source.json")
            metadata = {"sha256": hashlib.sha256(binary).hexdigest(), "timing_mode": "vblank"}
            receipt.write_text(json.dumps(metadata))
            self.assertEqual(load_mod(path)["timing_mode"], "vblank")
            metadata["sha256"] = "0" * 64
            receipt.write_text(json.dumps(metadata))
            with self.assertRaisesRegex(ValueError, "does not identify"):
                load_mod(path)


if __name__ == "__main__":
    unittest.main()
