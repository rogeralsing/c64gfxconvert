#!/usr/bin/env python3
"""Export the native renderer's object-space inputs for Line Font Lab."""

import json
import sys
from pathlib import Path


HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "mydemo" / "linedrawer"))

import ball_model
import cube_model as cube
from linedrawer import build_font


def scene(precision, vertices, faces, edges, edge_faces, camera_depth, motion_amplitudes):
    vertex_count = len(vertices) * (2 if precision == 6 else 1)
    incident_edges = [[] for _ in range(vertex_count)]
    for edge_id, (a, b) in enumerate(edges):
        incident_edges[a].append(edge_id)
        incident_edges[b].append(edge_id)
    return {
        "precision": precision,
        "vertices": vertices,
        "faces": faces,
        "edges": edges,
        "edgeFaces": edge_faces,
        "incidentEdges": incident_edges,
        "cameraDepth": camera_depth,
        "motionAmplitudes": motion_amplitudes,
    }


def main():
    _, tiles, _ = build_font()
    shapes = {"cube": scene(8, cube.VERTS, cube.FACES, cube.EDGES, cube.EDGE_FACES,
                            cube.CAM, cube.POSITION_AMPLITUDES)}
    for name in ("football", "globe"):
        vertices, faces, edges, edge_faces = ball_model.mesh_geometry(name)
        shapes[name] = scene(6, vertices, faces, edges, edge_faces,
                             ball_model.CAMERA_DEPTH, ball_model.MOTION_AMPLITUDES)

    data = {
        "bank": tiles,
        "sine": cube.SIN,
        "reciprocal": cube.RECIP,
        "farReciprocal": cube.FAR_RECIP,
        "depthMin": cube.DMIN,
        "depthNearMax": cube.DNEAR_MAX,
        "depthMax": cube.DMAX,
        "farBin": cube.FAR_BIN,
        "farFirst": cube.FAR_FIRST,
        "initialAngles": (cube.YAW0, cube.PITCH0, cube.ROLL0),
        "angleSteps": (cube.YAW_INC, cube.PITCH_INC, cube.ROLL_INC),
        "motionPhases": cube.POSITION_PHASES,
        "motionSteps": cube.POSITION_INCREMENTS,
        "shapes": shapes,
    }
    values = (f"  {json.dumps(key)}: {json.dumps(value, separators=(',', ':'))}"
              for key, value in data.items())
    (HERE / "join-study-data.js").write_text(
        "// Generated by build_join_study.py from the C64 wireframe models.\n"
        "globalThis.JOIN_STUDY_DATA = {\n" + ",\n".join(values) + "\n};\n"
    )


if __name__ == "__main__":
    main()
