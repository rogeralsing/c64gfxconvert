#!/usr/bin/env python3
"""Generate the browser's PAFLI PAL player from the pinned, checked AFLI engine."""

import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import tempfile


def build():
    root = Path(__file__).resolve().parents[2]
    spec = importlib.util.spec_from_file_location("afli_player", root / "afli-viewer/prg/build-prgs.py")
    afli = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(afli)
    original = (root / "ifli-viewer/diashow_eng.prg").read_bytes()
    if afli.sha256(original) != afli.PLAYER_SHA256:
        raise ValueError("The pinned GoDot PAL engine changed.")
    engine = bytearray(original[2:])
    engine[5:9] = b"8384"  # SYS $20c0 initializes the frame counter, then AFLI startup.
    patches = []
    for address, expected, replacement, purpose in afli.PATCHES:
        if address == 0x0e76:
            replacement = "0c"
            purpose = "initial phase B: hires, 40 columns, X-scroll 4"
        elif address == 0x0efa:
            replacement = "4c a0 20 ea ea ea ea ea"
            purpose = "close border and toggle X-scroll by four before the original bank switch"
        expected = bytes.fromhex(expected)
        replacement = bytes.fromhex(replacement)
        offset = address - 0x0801
        if engine[offset:offset + len(expected)] != expected or len(expected) != len(replacement):
            raise ValueError(f"Unexpected PAL instruction at ${address:04x}.")
        engine[offset:offset + len(expected)] = replacement
        patches.append({"address": f"${address:04x}", "expected": expected.hex(),
                        "replacement": replacement.hex(), "purpose": purpose})
    boot_source = root / "pafli/prg/boot.asm"
    with tempfile.TemporaryDirectory(prefix="c64-pafli-player-") as temporary:
        output = Path(temporary)
        subprocess.run([str(Path.home() / ".local/bin/kickass"), str(boot_source),
                        "-o", str(output / "boot.prg"), "-odir", str(output)], check=True)
        bootstrap = (output / "boot.prg").read_bytes()
    if bootstrap[:2] != b"\x00\x20" or len(bootstrap) > 0x1002:
        raise ValueError("Unexpected PAFLI bootstrap layout.")
    data = "/** Generated by pafli/prg/build-player.py. GoDot engine: see pafli/GoDot-LICENSE.txt. */\n"
    data += "const C64_PAFLI_PLAYER = Object.freeze({\n"
    for name, content in [("engine", engine), ("bootstrap", bootstrap[2:])]:
        data += f"  {name}: new Uint8Array([\n"
        for offset in range(0, len(content), 16):
            data += "    " + ", ".join(f"0x{byte:02x}" for byte in content[offset:offset + 16]) + ",\n"
        data += "  ]),\n"
    data += "});\n"
    (root / "pafli-player-data.js").write_text(data)
    receipt = {"player_source": afli.PLAYER_SOURCE, "player_sha256": afli.PLAYER_SHA256,
               "engine_sha256": hashlib.sha256(engine).hexdigest(),
               "bootstrap_sha256": hashlib.sha256(bootstrap).hexdigest(),
               "bootstrap_source_sha256": hashlib.sha256(boot_source.read_bytes()).hexdigest(),
               "shared_bootstrap_source_sha256": hashlib.sha256((root / "afli-viewer/prg/boot.asm").read_bytes()).hexdigest(),
               "entry": "$20c0 (SYS 8384)", "frame_end": "$20a0", "frame_counter": "$02f0",
               "phase_b_source_offset": -4, "phase_b_display_offset": 4,
               "visible_area": [28, 0, 320, 200], "patches": patches}
    (root / "pafli/prg/player.json").write_text(json.dumps(receipt, indent=2) + "\n")
    (root / "pafli/GoDot-LICENSE.txt").write_bytes((root / "afli-viewer/GoDot-LICENSE.txt").read_bytes())
    print("Generated pafli-player-data.js and player receipt.")


if __name__ == "__main__":
    build()
